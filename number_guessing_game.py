import random

secret = random.randint(1, 20)

max_attempts = 5
attempts = 0
won = False

while attempts < max_attempts:
    try:
        guess = int(input("Guess a number between 1 and 20: "))
    except ValueError:
        print("Please enter a whole number")
        continue

    attempts = attempts + 1

    if guess < secret:
        print("Too low")
    elif guess > secret:
        print("Too high")
    else:
        won = True
        break

if won:
    print(f"Correct! You took {attempts} attempts")
else:
    print(f"Game over. The secret was {secret}")

